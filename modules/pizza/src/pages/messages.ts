export type MessageKey = keyof typeof EN;
export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

const CATALOGUES: Record<string, Record<MessageKey, string>> = { en: EN, fi: FI };

/** The event's language, or English for one without a catalogue. */
export const languageOf = (value: unknown): string =>
  typeof value === "string" && Object.hasOwn(CATALOGUES, value) ? value : "en";

export const isKey = (key: string): key is MessageKey => Object.hasOwn(EN, key);

/** `t(key, values)` in `language`: `{name}` in a message takes `values.name`. */
export function translator(language: string): Translate {
  const catalogue = CATALOGUES[languageOf(language)] ?? EN;
  return (key, values = {}) =>
    catalogue[key].replace(/\{([a-z_]+)\}/g, (whole, name: string) =>
      Object.hasOwn(values, name) ? String(values[name]) : whole,
    );
}
